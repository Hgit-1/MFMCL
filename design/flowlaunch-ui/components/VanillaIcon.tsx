// 内容商店「原版游戏」分类的线性图标。
//
// ## 为什么不用方块贴图
//
// 抽屉菜单里并列五个分类：Mod（拼图）、整合包（包裹）、资源包（图片）、地图（地图）
// 都是 18px 的线性图标，只有「原版游戏」用的是一张 16×16 的像素贴图。
// 两种表现手法放在同一列里会显得突兀：
//   - 线稿是单一主色描边，像素贴图是彩色填充，视觉重量差了一档；
//   - 贴图需要 `image-rendering: pixelated` 放大，边缘是硬的；线稿是抗锯齿的；
//   - 18px 放小后，16×16 的贴图只剩 18 个像素可辨，草与土的分界糊成一团。
//
// ## 为什么最终是手柄，而不是草方块
//
// 试过四种「草方块」写法，全部失败，原因值得记下来：
//
// 1. **正面方块 + 顶边起伏草层** → 18px 下顶部凸起读成日历页角的装订环。
// 2. **等距立方体 + 顶面强调线** → 轮廓与「整合包」图标完全相同，18px 下糊掉后
//    两个分类无法分辨。这比风格突兀更糟，所以直接否掉。
// 3. **俯视方块 + 斜向分界** → 斜线读成「图片」或「禁用」。
// 4. **方块 + 顶带实心草皮** → 与「资源包」的方框轮廓撞车。
//
// 共同的根本问题：**「草方块」的识别特征是颜色分界，而单色线稿没有颜色可用**。
// 靠轮廓表达又需要比 18px 更细的结构。继续强行画，只会得到一个「某种认不出的
// 方块」——那比风格不统一更难用。
//
// 所以换一个在 18px 里本来就成立的隐喻：**游戏手柄**。
// 这个分类回答的是「这里有什么内容」，答案是「游戏本体」，与 Mod / 整合包 /
// 资源包 / 地图这些附加内容相对。手柄轮廓有两条清晰的圆肩与一条下缘，
// 缩小后仍能辨认，且与另四项的轮廓（拼图 / 包裹 / 图片 / 地图）完全不冲突。
//
// ## 为何不做成彩色
//
// 保持一致：这一列只有主色描边，图标随行文字一起在选中态变主色。
// 单独给一个彩色图标会破坏这个联动，也重新引入了「视觉重量不等」的问题。

