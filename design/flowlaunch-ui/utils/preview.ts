// 预览数据开关。
//
// ## 要解决的问题
//
// 浏览器里没有 Rust 后端，`vite dev` 下实例列表、模组清单、版本清单都是空的，
// 游戏库只会显示「还没有游戏」——恰是最需要调外观的页面在 Design 模式里看不到
// 任何内容。所以这些页面需要一份示例数据。
//
// 但示例数据**绝不能出现在打包产物里**：用户装了启动器却看到「纯净生存 1.21.1」
// 这种别人的实例，会以为程序出了故障；更糟的是有人可能真的去点「启动」。
//
// ## 为什么用编译期常量而不是运行时判断
//
// `import.meta.env.DEV` 由 Vite 在构建时静态替换成 `true`/`false`。写成
// `if (PREVIEW_DATA)` 时，生产构建里整个分支是 `if (false) {...}`，Rollup 的
// tree-shaking 会把示例数据连同它的字符串一起删掉——产物里连这些字都不会出现。
//
// 用运行时判断（例如检查 `location.hash` 或 localStorage 开关）做不到这一点：
// 数据必须存在于产物中，只是不渲染。那样既增大体积，也让「发布版里有没有假数据」
// 变成一个需要逐处核对的问题。
//
// ## 边界
//
// 这个开关只控制「示例数据」，不控制预览模式的**能力边界**：即使在 dev 下，
// 创建实例、安装、启动这些真正会改动后端的操作仍然一起报错，不会伪造成功。

/** 是否允许使用示例数据。生产构建中恒为 false，相关分支会被完全移除。 */
export const PREVIEW_DATA: boolean = import.meta.env.DEV;
